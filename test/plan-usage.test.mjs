test('(d) hiveku-orient carries the rules and the limit line byte for byte, in their places', () => {
  const orient = read('skills/hiveku-orient/SKILL.md');
  const start = orient.indexOf('## Your plan and its limits');
  assert.ok(start > 0, 'orient has the section "Your plan and its limits"');
  const section = orient.slice(start, orient.indexOf('## Approvals and escalation', start));
  assert.ok(section.includes(PLAN_USAGE_INSTRUCTIONS), 'the section carries the rules byte for byte');
  assert.match(section, /`account_usage_get`/);
  assert.match(flat(section), /`limit_kind` at the top/);
  const defects = orient.slice(orient.indexOf('**Not Hiveku defects - file nothing.**'), orient.indexOf('- **Only problems you hit yourself.**'));
  const refusal = defects.indexOf('memory_write_refused');
  assert.ok(refusal > 0, 'the defects list names the memory refusal');
  assert.ok(defects.indexOf(PLAN_LIMIT_LINE) > refusal, 'the limit line follows the memory refusal, byte for byte');
  // The department refusal, in the MCP server's words (department-chat.service.ts, MCP #225).
  assert.ok(
    flat(orient).includes(
      "\"This account cannot use the '<x>' department: its plan does not include it, or it is not released to this account yet. list_departments shows what it can use; an owner or admin sees the plan options in Settings > Billing.\"",
    ),
    'orient quotes the department refusal in its new words',
  );
});


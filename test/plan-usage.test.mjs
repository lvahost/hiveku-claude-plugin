/** What stopped being true (plan section 8), each with the reason. Matched on whitespace-collapsed prose. */
const STALE = [
  [/voice add-on/i, 'phones come with every paid plan; 402 voice_not_enabled means they are not set up yet'],
  [/Premium-gated/i, 'X posts come with every paid plan: Starter 5, Standard 30, Premium 60 a month'],
  [
    /negative (DataForSEO )?balance|DataForSEO balance (can go|went|is) negative/i,
    "a research 402 is seo_research_limit: this month's research lookups are used up",
  ],
  [/100 runs (per|a) month/i, 'automation runs by plan: Free 25, Starter 500, Standard 2,500, Premium 10,000'],
  [/MCP calls will never be refused by it/, 'workflow_enable answers 402 plan_limit_reached past the active automations'],
  [/does not have access to the '<x>' department\. Upgrade or enable it/, "the refusal now reads \"cannot use the '<x>' department\""],
];

function staleClaims(text) {
  const prose = flat(text);
  return STALE.filter(([re]) => re.test(prose)).map(([re, why]) => `${re} (${why})`);
}

test('(f) no skill, command or agent says what stopped being true', () => {
  const offenders = [];
  for (const rel of walkMarkdown(['skills', 'commands', 'agents'])) {
    for (const claim of staleClaims(read(rel))) offenders.push(`${rel}: ${claim}`);
  }
  assert.deepEqual(offenders, [], `stale plan texts:\n  ${offenders.join('\n  ')}`);
});

test('(f) the stale-text detectors catch the old wording (negative control)', () => {
  const old = [
    'means the Voice add-on / tenant is not enabled yet',
    'X posting is Premium-gated',
    'The DataForSEO balance can go NEGATIVE',
    'A 402 is a negative balance',
    'The default included allowance is 100 runs per month.',
    'so your MCP calls will never be refused by it.',
    "\"This account does not have access to the '<x>' department. Upgrade or enable it in the dashboard settings.\"",
  ];
  for (const text of old) assert.ok(staleClaims(text).length > 0, `the detectors miss: ${text}`);
});


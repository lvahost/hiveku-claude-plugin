/**
 * The account's plan and its limits on the plugin side (agent plan and usage,
 * notes/plans-update-2026-10-09/agent-plan-usage-plan.md sections 3, 5, 6 and
 * 8). The builder writes the words once (builder #1332,
 * src/lib/platform-guide/plan-usage.ts, served with no key at
 * /api/public/platform-guide/plan-usage) and every surface copies them byte
 * for byte; the MCP server carries them and lifts limit_kind, message, hint
 * and billing_url to the top of a refused tool's error (MCP #225).
 *
 * Pinned here:
 *   (a) account_usage_get is advertised without a search and survives a focus
 *       filter, like the other reads a session orients with;
 *   (b) the shim's two texts are the builder's, byte for byte (sha256), static,
 *       and reach a bound folder's initialize: the rules on lines of their own
 *       after the platform rules, the limit line right after the
 *       memory_write_refused sentence; an unbound folder gets neither;
 *   (c) the committed tool index carries the builder's account_usage_get
 *       description, byte for byte (the release regenerates the index from the
 *       live server);
 *   (d) hiveku-orient carries the rules and the limit line byte for byte, the
 *       limit line after the memory refusal in "Not Hiveku defects", and the
 *       department refusal in the MCP server's new words;
 *   (e) the commands that start work the plan counts call account_usage_get,
 *       and /hiveku:start reads it instead of account_entitlements;
 *   (f) no skill, command or agent says what stopped being true (a "Voice
 *       add-on", X "Premium-gated", a negative DataForSEO balance, 100 runs a
 *       month, MCP calls never refused at the active-automation number, the
 *       old department refusal), and the places a session meets Outbound,
 *       automation runs and X posts state today's numbers.
 *       lib/dept-manifest.json is generated by hiveku-vscode (npm run
 *       sync:registry, from src/setupPlaybooks.ts), so its copy is fixed at that
 *       source and is not scanned here.
 *   (g) the session-start hook prints the builder's limit line, byte for byte,
 *       right after the memory_write_refused line, in a bound folder only.
 *       Claude Code shows a server's initialize instructions only up to 2,048
 *       characters, and the plan rules start near character 1,850 of the
 *       shim's, so (b) proves the text is sent, not that the model sees it. The
 *       hook output reaches every session whole; (g) runs the real hook.
 *   (h) crm_estimate_send's SMS branch is told in MCP #225's words: the
 *       builder route answers an error (channel sms) or sms.ok false beside
 *       the email result (channel both), never a 402 voice_not_enabled.
 * The stale-text detectors have a negative control on the old wording.
 */
